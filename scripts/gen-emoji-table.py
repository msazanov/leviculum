#!/usr/bin/env python3
"""Generate loquax's emoji table, `loquax/emoji/emoji.tsv`, from Unicode data.

The picker of loquax on Android (1137) and any later one reads this table:
which emoji there are, in which category and order, their English and
German names for the search, and the skin tone variants a long press
offers. The emoji themselves are text the system's emoji font draws; only
this list is data.

Inputs, none checked in (all under the Unicode Licence V3, whose text is
`loquax/emoji/LICENSE-UNICODE.txt`):

  emoji-test.txt   https://www.unicode.org/Public/emoji/15.1/emoji-test.txt
                   sha256 d876ee249aa28eaa76cfa6dfaa702847a8d13b062aa488d465d0395ee8137ed9
  CLDR 44 German   https://raw.githubusercontent.com/unicode-org/cldr/release-44/
                   common/annotations/de.xml
                   sha256 ffcf118a9416c65b02e5655403fdd03437765623d040533f6443bd15e35e97a2
                   common/annotationsDerived/de.xml
                   sha256 b7bb5b3e11bf623a6afdf76366fec11f38e08fc59534077983d305b7a87b8a67

Emoji 15.1 is what Android 15 (API 35, the app's target) draws; CLDR 44 is
the release that names it. A phone on an older Android lacks the newest
emoji, and the picker leaves out what its font cannot draw.

    scripts/gen-emoji-table.py EMOJI_TEST ANNOTATIONS_DE DERIVED_DE > loquax/emoji/emoji.tsv

The table, one line each:

    @<category>                          a category begins
    <emoji>\t<English>\t<German>[\t<variants>]

Only fully-qualified emoji, in CLDR order, without the Component group
(the bare skin tones and hair styles). An emoji with one skin tone is a
variant of the emoji without it, space-separated in the fourth column; one
with two different tones (a couple, a handshake of two hands) is left out,
so a long press offers the five tones and nothing more.
"""

from __future__ import annotations

import sys
import xml.etree.ElementTree as ET

CATEGORIES = {
    "Smileys & Emotion": "smileys",
    "People & Body": "people",
    "Animals & Nature": "animals",
    "Food & Drink": "food",
    "Travel & Places": "travel",
    "Activities": "activities",
    "Objects": "objects",
    "Symbols": "symbols",
    "Flags": "flags",
}
TONES = {0x1F3FB, 0x1F3FC, 0x1F3FD, 0x1F3FE, 0x1F3FF}
VS16 = 0xFE0F


def names(*paths: str) -> dict[str, str]:
    """CLDR's short (tts) names by the emoji, written without U+FE0F."""
    out: dict[str, str] = {}
    for path in paths:
        for node in ET.parse(path).getroot().iter("annotation"):
            if node.get("type") == "tts" and node.text:
                out[node.get("cp", "").replace("️", "")] = node.text.strip()
    return out


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__.strip().splitlines()[0], file=sys.stderr)
        print("usage: gen-emoji-table.py EMOJI_TEST ANNOTATIONS_DE DERIVED_DE", file=sys.stderr)
        return 2
    german = names(sys.argv[2], sys.argv[3])
    # (category, [base, ...]); a base is [emoji, english, variants]
    groups: list[tuple[str, list[list]]] = []
    by_key: dict[tuple[int, ...], list] = {}
    category = None
    missing = 0
    with open(sys.argv[1], encoding="utf-8") as f:
        for line in f:
            if line.startswith("# group:"):
                category = CATEGORIES.get(line.split(":", 1)[1].strip())
                if category:
                    groups.append((category, []))
                continue
            if category is None or line.startswith("#") or ";" not in line:
                continue
            points, rest = line.split(";", 1)
            if not rest.strip().startswith("fully-qualified"):
                continue
            cps = [int(p, 16) for p in points.split()]
            english = rest.split("#", 1)[1].split(None, 2)[2].strip()
            emoji = "".join(map(chr, cps))
            tones = {c for c in cps if c in TONES}
            key = tuple(c for c in cps if c not in TONES and c != VS16)
            if tones:
                base = by_key.get(key)
                if base is not None and len(tones) == 1:
                    base[2].append(emoji)
                continue
            base = [emoji, english, []]
            by_key[key] = base
            groups[-1][1].append(base)
    out = sys.stdout
    out.write("# loquax's emoji table: Emoji 15.1, names from CLDR 44.\n")
    out.write("# Generated by scripts/gen-emoji-table.py; do not edit.\n")
    out.write("# Unicode data, Unicode Licence V3: loquax/emoji/LICENSE-UNICODE.txt\n")
    for category, bases in groups:
        out.write(f"@{category}\n")
        for emoji, english, variants in bases:
            name = german.get(emoji.replace("️", ""))
            if name is None:
                missing += 1
                name = english
            cols = [emoji, english, name] + ([" ".join(variants)] if variants else [])
            out.write("\t".join(cols) + "\n")
    if missing:
        print(f"{missing} emoji without a German name kept their English one", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
