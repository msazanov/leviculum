#!/usr/bin/env python3
"""The board firmware's module graph, as a census (Codeberg #469, 957).

docs/src/concepts/firmware-layers.md moves `leviculum-nrf`'s modules into the
orchestration crate bottom-up, and which module can move next is a property of
the graph: a module moves once everything it reaches has moved or is a seam.
Step 2's place in the order was decided wrong on the page because the graph
was read once, by hand, and never again. This script records it, and
scripts/nrf-module-reach.txt is the record: every commit that moves a file
regenerates it, so the file's history is the extraction's.

What it counts
--------------

For every `*.rs` under `leviculum-nrf/src` (the bind crate) and
`leviculum-nrf/firmware/src` (the orchestration crate), one line

    <path> (<lines>): <sorted reach>

where the path is relative to `leviculum-nrf`, `<lines>` is the file's line
count, and the reach is the set of `<ident>` names the file spells as
`crate::<ident>`, minus the file's own module name (`foo.rs` and `foo/mod.rs`
are `foo`; `lib.rs` and `bin/*.rs` are no module). The text is read as it
is, doc comments included: an intra-doc link to `crate::x` is a reach the
page has to account for as much as a call is. Macros count by name
(`crate::log_critical!` is `log_critical`), and so do the `lib.rs` helpers,
because a helper that has not moved holds its callers exactly as a module
does.

A binary names its crate `leviculum_nrf::`, not `crate::`, so its reach is
empty here; it is listed for its line count.

Usage:
    python3 scripts/nrf-module-reach.py            # the gate: diff tree vs file
    python3 scripts/nrf-module-reach.py --write    # regenerate the file
    python3 scripts/nrf-module-reach.py --selftest # positive control

Exit 0 = the census file matches the tree.
Exit 1 = it does not (the diff is printed), or the selftest failed.
"""

from __future__ import annotations

import contextlib
import difflib
import io
import re
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NRF = ROOT / "leviculum-nrf"
TREES = ("src", "firmware/src")
CENSUS = ROOT / "scripts" / "nrf-module-reach.txt"

REACH_RE = re.compile(r"crate::([a-z_][a-z0-9_]*)")

HEADER = """\
# leviculum-nrf's module graph (Codeberg #469, 957). Generated by
# scripts/nrf-module-reach.py --write; `just nrf-module-reach` fails on any
# difference from the tree. One line per file under leviculum-nrf/src and
# leviculum-nrf/firmware/src: path (lines): the `crate::<name>` names it
# reaches, its own module excluded. See the script's header for the rules.
"""


def own_module(rel: Path) -> str | None:
    """The module name a file is, or None for a crate root or a binary."""
    if rel.name == "lib.rs" or "bin" in rel.parts:
        return None
    if rel.name == "mod.rs":
        return rel.parent.name
    return rel.stem


def census(nrf: Path) -> str:
    lines = []
    for tree in TREES:
        base = nrf / tree
        for f in sorted(base.rglob("*.rs")):
            text = f.read_text()
            rel_in_tree = f.relative_to(base)
            own = own_module(rel_in_tree)
            reach = sorted(set(REACH_RE.findall(text)) - {own})
            count = len(text.splitlines())
            path = f.relative_to(nrf).as_posix()
            lines.append(f"{path} ({count}): {' '.join(reach)}".rstrip())
    return HEADER + "\n".join(lines) + "\n"


def check(nrf: Path, census_file: Path) -> int:
    want = census(nrf)
    have = census_file.read_text() if census_file.exists() else ""
    if want == have:
        print(f"[nrf-module-reach] ok   {census_file.name} matches the tree "
              f"({sum(not l.startswith('#') for l in want.splitlines())} files)")
        return 0
    diff = difflib.unified_diff(
        have.splitlines(), want.splitlines(),
        f"{census_file.name} (committed)", "tree (now)", lineterm="")
    print("[nrf-module-reach] FAIL the module graph moved and the census did not:")
    for line in diff:
        print(f"  {line}")
    print("[nrf-module-reach] Regenerate with `python3 scripts/nrf-module-reach.py "
          "--write` and commit it with the move.")
    return 1


def selftest() -> int:
    """The unmodified census passes; one injected false reach line is refused."""
    with tempfile.TemporaryDirectory() as tmp:
        copy = Path(tmp) / "nrf-module-reach.txt"
        shutil.copy(CENSUS, copy)
        with contextlib.redirect_stdout(io.StringIO()):
            rc = check(NRF, copy)
        if rc != 0:
            print("[nrf-module-reach] SELFTEST FAIL: the unmodified copy was refused")
            return 1
        text = copy.read_text().splitlines(keepends=True)
        for i, line in enumerate(text):
            if line.startswith("src/clock.rs ") or line.startswith("firmware/src/clock.rs "):
                text[i] = line.rstrip("\n") + " usb\n"
                break
        else:
            print("[nrf-module-reach] SELFTEST FAIL: no clock.rs line to inject into")
            return 1
        copy.write_text("".join(text))
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            rc = check(NRF, copy)
        print(f"[nrf-module-reach] selftest: injected `{text[i].rstrip()}`, "
              f"the check exited {rc} saying:")
        for line in out.getvalue().splitlines():
            print(f"[nrf-module-reach]   | {line}")
        if rc != 1:
            print("[nrf-module-reach] SELFTEST FAIL: an injected false reach was not refused")
            return 1
    print("[nrf-module-reach] selftest ok: a false reach line in the census is refused")
    return 0


def main(argv: list[str]) -> int:
    if argv == ["--write"]:
        CENSUS.write_text(census(NRF))
        print(f"[nrf-module-reach] wrote {CENSUS.relative_to(ROOT)}")
        return 0
    if argv == ["--selftest"]:
        return selftest()
    if argv:
        print(__doc__)
        return 2
    return check(NRF, CENSUS)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
