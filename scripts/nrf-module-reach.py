#!/usr/bin/env python3
"""The board firmware's module graph, as a census (Codeberg #469, 957).

docs/src/concepts/firmware-layers.md moves `leviculum-nrf`'s modules into the
orchestration crate bottom-up, and which module can move next is a property of
the graph: a module moves once everything it reaches has moved or is a seam.
Step 2's place in the order was decided wrong on the page because the graph
was read once, by hand, and never again. This script records it, and
scripts/nrf-module-reach.txt is the record: every commit that moves a file
regenerates it, so the file's history is the extraction's.

What it counts
--------------

For every `*.rs` under `leviculum-nrf/src` (the bind crate) and
`leviculum-nrf/firmware/src` (the orchestration crate), one line

    <path> (<lines>): <sorted reach>

where the path is relative to `leviculum-nrf`, `<lines>` is the file's line
count, and the reach is the set of `<ident>` names the file spells as
`crate::<ident>`, minus the file's own module name (`foo.rs` and `foo/mod.rs`
are `foo`; `lib.rs` and `bin/*.rs` are no module). The text is read as it
is, doc comments included: an intra-doc link to `crate::x` is a reach the
page has to account for as much as a call is. Macros count by name
(`crate::log_critical!` is `log_critical`), and so do the `lib.rs` helpers,
because a helper that has not moved holds its callers exactly as a module
does.

A binary names its crate `leviculum_nrf::`, not `crate::`, so its reach is
empty here; it is listed for its line count.

The seam vocabulary (958)
-------------------------

The reach says WHICH modules hold a file in the bind crate; the vocabulary
says with WHAT. scripts/nrf-seam-vocabulary.txt lists, for every `*.rs` under
`leviculum-nrf/src` except the binaries, every item it names below the bind
line, one line per file and item:

    <path>: <item> [xN] [doc xM]

where the item is

* `<bind>::<path>` for a `crate::<bind>::<path>` with `<bind>` in
  `BIND_MODULES` (a bare `crate::<bind>` is the item `<bind>`; a brace group
  `crate::<bind>::{a, b::C}` is one item per entry), or
* `<name>` for a `crate::<name>` that `lib.rs` defines rather than declares as
  a module: a helper, a static, a macro. A name `lib.rs` re-exports from
  `leviculum_firmware` (`log`, `log_critical`, `postmortem_query`, ...) has
  already moved to stratum 2 and holds nothing, so it is not counted.

A file's references to its own module are internal and move with it, so
they are left out as in the reach. `xN` counts code, ordinary `//` comments
included; `doc xM` counts doc-comment lines (`///`, `//!`), the split the
chip guard (`scripts/check-firmware-no-chip.sh`) makes: an intra-doc link is a
reach the page accounts for, but it is not a call a seam has to carry.

Usage:
    python3 scripts/nrf-module-reach.py            # the gate: diff tree vs files
    python3 scripts/nrf-module-reach.py --write    # regenerate both files
    python3 scripts/nrf-module-reach.py --selftest # positive control, both files

Exit 0 = both census files match the tree.
Exit 1 = one does not (the diff is printed), or the selftest failed.
"""

from __future__ import annotations

import contextlib
import difflib
import io
import re
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NRF = ROOT / "leviculum-nrf"
TREES = ("src", "firmware/src")
CENSUS = ROOT / "scripts" / "nrf-module-reach.txt"
VOCABULARY = ROOT / "scripts" / "nrf-seam-vocabulary.txt"

REACH_RE = re.compile(r"crate::([a-z_][a-z0-9_]*)")

# The modules that stay in the bind crate: the backends row of
# docs/src/concepts/firmware-layers.md, "The problem, measured". A reading of
# the page, not a fact of the tree; when the page moves a module across the
# line, this list moves with it.
BIND_MODULES = (
    "ble", "usb", "baseboard", "boards", "sx1262", "radio", "qspi", "flash",
    "record_store", "radio_store", "rng", "led", "button", "feedback",
    "display", "st7789", "battery", "gnss", "motion", "vext",
)

# `crate::<name>` with its `::`-path and an optional brace group after it.
ITEM_RE = re.compile(
    r"crate::([a-z_][a-z0-9_]*)((?:::[A-Za-z_][A-Za-z0-9_]*)*)(::\{[^{}]*\})?")
MOD_DECL_RE = re.compile(r"^\s*(?:pub(?:\([a-z]+\))?\s+)?mod\s+([a-z_][a-z0-9_]*)", re.M)
FIRMWARE_USE_RE = re.compile(r"^\s*pub use leviculum_firmware::([^;]+);", re.M)

HEADER = """\
# leviculum-nrf's module graph (Codeberg #469, 957). Generated by
# scripts/nrf-module-reach.py --write; `just nrf-module-reach` fails on any
# difference from the tree. One line per file under leviculum-nrf/src and
# leviculum-nrf/firmware/src: path (lines): the `crate::<name>` names it
# reaches, its own module excluded. See the script's header for the rules.
"""

VOCABULARY_HEADER = """\
# leviculum-nrf's seam vocabulary (Codeberg #469, 958). Generated by
# scripts/nrf-module-reach.py --write; `just nrf-module-reach` fails on any
# difference from the tree. One line per file under leviculum-nrf/src (the
# binaries excepted) and item it names below the bind line:
#   path: item [xN code] [doc xM doc-comment lines]
# An item is `<bind>::<path>` for a module in the bind-crate list, or a name
# lib.rs defines. The bind-crate list is the backends row of
# docs/src/concepts/firmware-layers.md, "The problem, measured", read into
# the script's BIND_MODULES; it is a reading of the page and moves with it:
#   {bind}
# See the script's header for the rules.
"""


def own_module(rel: Path) -> str | None:
    """The module name a file is, or None for a crate root or a binary."""
    if rel.name == "lib.rs" or "bin" in rel.parts:
        return None
    if rel.name == "mod.rs":
        return rel.parent.name
    return rel.stem


def census(nrf: Path) -> str:
    lines = []
    for tree in TREES:
        base = nrf / tree
        for f in sorted(base.rglob("*.rs")):
            text = f.read_text()
            rel_in_tree = f.relative_to(base)
            own = own_module(rel_in_tree)
            reach = sorted(set(REACH_RE.findall(text)) - {own})
            count = len(text.splitlines())
            path = f.relative_to(nrf).as_posix()
            lines.append(f"{path} ({count}): {' '.join(reach)}".rstrip())
    return HEADER + "\n".join(lines) + "\n"


def lib_items(nrf: Path) -> tuple[set[str], set[str]]:
    """`lib.rs`'s declared modules, and the names it re-exports from stratum 2."""
    text = (nrf / "src" / "lib.rs").read_text()
    modules = set(MOD_DECL_RE.findall(text))
    moved = set()
    for spec in FIRMWARE_USE_RE.findall(text):
        group = re.search(r"\{([^}]*)\}", spec)
        names = group.group(1).split(",") if group else [spec]
        moved |= {n.strip().split("::")[-1] for n in names if n.strip()}
    return modules, moved


def items_on(line: str, own: str | None, modules: set[str], moved: set[str]) -> list[str]:
    """The below-the-line items one source line names."""
    out = []
    for m in ITEM_RE.finditer(line):
        head, path, group = m.group(1), m.group(2), m.group(3)
        if head == own:
            continue
        if head in BIND_MODULES:
            base = head + path
            if group:
                for entry in group[3:-1].split(","):
                    entry = entry.strip().split(" as ")[0].strip()
                    if entry:
                        out.append(base if entry == "self" else f"{base}::{entry}")
            else:
                out.append(base)
        elif head not in modules and head not in moved:
            out.append(head)
    return out


def vocabulary(nrf: Path) -> str:
    modules, moved = lib_items(nrf)
    base = nrf / "src"
    lines = []
    for f in sorted(base.rglob("*.rs")):
        rel_in_tree = f.relative_to(base)
        if "bin" in rel_in_tree.parts:
            continue
        own = own_module(rel_in_tree)
        code: dict[str, int] = {}
        doc: dict[str, int] = {}
        for line in f.read_text().splitlines():
            tally = doc if line.lstrip().startswith(("///", "//!")) else code
            for item in items_on(line, own, modules, moved):
                tally[item] = tally.get(item, 0) + 1
        path = f.relative_to(nrf).as_posix()
        for item in sorted(set(code) | set(doc)):
            counts = []
            if item in code:
                counts.append(f"x{code[item]}")
            if item in doc:
                counts.append(f"doc x{doc[item]}")
            lines.append(f"{path}: {item} {' '.join(counts)}")
    header = VOCABULARY_HEADER.format(bind=" ".join(BIND_MODULES))
    return header + "\n".join(lines) + "\n"


def check(nrf: Path, census_file: Path, make=census) -> int:
    want = make(nrf)
    have = census_file.read_text() if census_file.exists() else ""
    if want == have:
        print(f"[nrf-module-reach] ok   {census_file.name} matches the tree "
              f"({sum(not l.startswith('#') for l in want.splitlines())} lines)")
        return 0
    diff = difflib.unified_diff(
        have.splitlines(), want.splitlines(),
        f"{census_file.name} (committed)", "tree (now)", lineterm="")
    print("[nrf-module-reach] FAIL the module graph moved and the census did not:")
    for line in diff:
        print(f"  {line}")
    print("[nrf-module-reach] Regenerate with `python3 scripts/nrf-module-reach.py "
          "--write` and commit it with the move.")
    return 1


def selftest_vocabulary() -> int:
    """The unmodified vocabulary passes; one injected false item line is refused."""
    with tempfile.TemporaryDirectory() as tmp:
        copy = Path(tmp) / "nrf-seam-vocabulary.txt"
        shutil.copy(VOCABULARY, copy)
        with contextlib.redirect_stdout(io.StringIO()):
            rc = check(NRF, copy, vocabulary)
        if rc != 0:
            print("[nrf-module-reach] SELFTEST FAIL: the unmodified vocabulary was refused")
            return 1
        injected = "src/chtm.rs: usb::init x1"
        text = copy.read_text().splitlines(keepends=True)
        body = [l for l in text if not l.startswith("#")] + [injected + "\n"]
        copy.write_text("".join([l for l in text if l.startswith("#")] + sorted(body)))
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            rc = check(NRF, copy, vocabulary)
        print(f"[nrf-module-reach] selftest: injected `{injected}`, "
              f"the check exited {rc} saying:")
        for line in out.getvalue().splitlines():
            print(f"[nrf-module-reach]   | {line}")
        if rc != 1:
            print("[nrf-module-reach] SELFTEST FAIL: an injected false item was not refused")
            return 1
    print("[nrf-module-reach] selftest ok: a false item line in the vocabulary is refused")
    return 0


def selftest() -> int:
    """The unmodified census passes; one injected false reach line is refused."""
    with tempfile.TemporaryDirectory() as tmp:
        copy = Path(tmp) / "nrf-module-reach.txt"
        shutil.copy(CENSUS, copy)
        with contextlib.redirect_stdout(io.StringIO()):
            rc = check(NRF, copy)
        if rc != 0:
            print("[nrf-module-reach] SELFTEST FAIL: the unmodified copy was refused")
            return 1
        text = copy.read_text().splitlines(keepends=True)
        for i, line in enumerate(text):
            if line.startswith("src/clock.rs ") or line.startswith("firmware/src/clock.rs "):
                text[i] = line.rstrip("\n") + " usb\n"
                break
        else:
            print("[nrf-module-reach] SELFTEST FAIL: no clock.rs line to inject into")
            return 1
        copy.write_text("".join(text))
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            rc = check(NRF, copy)
        print(f"[nrf-module-reach] selftest: injected `{text[i].rstrip()}`, "
              f"the check exited {rc} saying:")
        for line in out.getvalue().splitlines():
            print(f"[nrf-module-reach]   | {line}")
        if rc != 1:
            print("[nrf-module-reach] SELFTEST FAIL: an injected false reach was not refused")
            return 1
    print("[nrf-module-reach] selftest ok: a false reach line in the census is refused")
    return selftest_vocabulary()


def main(argv: list[str]) -> int:
    if argv == ["--write"]:
        CENSUS.write_text(census(NRF))
        VOCABULARY.write_text(vocabulary(NRF))
        print(f"[nrf-module-reach] wrote {CENSUS.relative_to(ROOT)}, "
              f"{VOCABULARY.relative_to(ROOT)}")
        return 0
    if argv == ["--selftest"]:
        return selftest()
    if argv:
        print(__doc__)
        return 2
    return check(NRF, CENSUS) | check(NRF, VOCABULARY, vocabulary)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
