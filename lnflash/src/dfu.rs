//! The **transport** axis, second kind: Nordic's legacy serial DFU, the way
//! `adafruit-nrfutil dfu serial` speaks it to an Adafruit nRF52 bootloader.
//!
//! Some bootloaders publish no UF2 drive at all. The SenseCAP T1000-E on our
//! rig is one: its bootloader (USB `2886:0057`) answers the 1200-baud touch
//! with a CDC port and nothing else, so [`transport`](crate::transport) has
//! nothing to copy onto (Codeberg #452). This module is what writes such a
//! board instead, and it is the whole of the second transport: the flow
//! decides when, this decides the bytes.
//!
//! Everything on the wire follows the reference implementation installed on
//! the rig host, adafruit-nrfutil 0.5.3.post16 (`nordicsemi/dfu/` in its
//! package), and the tests hold this module to bytes that tool produced
//! (`tests/fixtures/dfu/`, regenerated by the `capture.py` beside them):
//!
//! | what | reference |
//! |---|---|
//! | SLIP framing: `0xC0` both ends, `0xC0`→`DB DC`, `0xDB`→`DB DD` | `dfu_transport_serial.py:359-365`, `util.py:158-179` |
//! | HCI header: seq, ack = seq+1, integrity and reliable bits, type 14, 12-bit length, two's-complement checksum | `dfu_transport_serial.py:341-345`, `util.py:82-102`, constants `:317-319` |
//! | frame CRC16 (CCITT, init `0xFFFF`) over header and payload, little-endian | `dfu_transport_serial.py:353-356`, `crc16.py:160-176` |
//! | sequence numbers 1, 2, … mod 8, one per frame | `dfu_transport_serial.py:335-338` |
//! | init packet: device type, device revision, application version, SoftDevice list with its length, image CRC16, all little-endian | `init_packet.py:69-131`, `package.py:80-83` (defaults), `package.py:196-198` (CRC16 for DFU version 0.5) |
//! | init frame: type 1, the packet, two bytes of padding | `dfu_transport_serial.py:147-155` |
//! | start frame: type 3, mode 4 (application), SoftDevice, bootloader and application sizes | `dfu_transport_serial.py:171-184`, `dfu_transport.py:55-72`, `model.py:32-36` |
//! | data frames: type 4, 512 bytes at most | `dfu_transport_serial.py:76-77`, `:194-207` |
//! | flow control: erase wait after start, a page-write pause every eighth data frame and after the last | `dfu_transport_serial.py:65-74`, `:157-159`, `:184`, `:219-225` |
//! | stop frame: type 5, then the activate wait | `dfu_transport_serial.py:227-230`, `:161-169`, `dfu.py:208-215` |
//! | order: start, init, data, stop | `dfu.py:198-215` |
//! | image: hex to binary from the lowest address, `0xFF` in gaps, rounded up to a word | `package.py:322-331`, `nrfhex.py:109-143` |
//!
//! Three places where this does more than the reference, all on the side of
//! saying so rather than carrying on:
//!
//! * **The acknowledgement number is checked.** nrfutil writes a frame,
//!   waits for any frame back and moves on (`dfu_transport_serial.py:239-246`:
//!   `last_ack` starts as `None`, so the loop always breaks after the first
//!   write). The bootloader answers a frame it did not take with the number
//!   it still expects (`hci_transport.c`, `rx_vendor_specific_pkt_type_handle`
//!   in the Adafruit bootloader's SDK), so that number is a NACK, and here a
//!   NACK resends the frame and, after [`SEND_ATTEMPTS`], fails the flash.
//! * **An image that does not start at the application base is refused.**
//!   The protocol carries no address: the bootloader writes the first byte to
//!   its own application start whatever the image was linked for. That is
//!   how an RNode build linked for `0x51000` landed at `0x27000` on a T114
//!   and went dark (docs/src/concepts/lnode-flashing.md).
//! * **A port that goes away is the end, not a retry.** The bootloader resets
//!   on an init packet it refuses (`dfu_transport_serial.c:225-228`,
//!   `APP_ERROR_CHECK` on `dfu_init_pkt_complete`, whose fault handler is
//!   `NVIC_SystemReset`), and from the host that looks exactly like a cable
//!   pulled mid-image. [`Error::Gone`] says which frame it happened after.
//!
//! What the bootloader checks and the host cannot: the device type has to be
//! `0x0052` and the SoftDevice it runs has to be in the init packet's list
//! (`dfu_init.c`, `dfu_init_prevalidate`). There is no way to read either off
//! the board first. The start packet erases the application area before the
//! init packet is looked at (`dfu_single_bank.c`, `dfu_start_pkt_handle`), so
//! a refused init packet leaves the board in its bootloader with no
//! application — recoverable by a correct flash, which is what
//! [`Stage::erased_before`] lets the flow tell the user.

use std::fmt;
use std::io;
use std::time::{Duration, Instant};

use crate::ihex::Span;
use crate::uf2::Image;

/// The device revision `dfu genpkg` writes when none is given
/// (`package.py:81`). The bootloader only checks it for SoftDevice and
/// bootloader updates (`dfu_init.c`), never for an application.
pub const DEVICE_REVISION_ANY: u16 = 0xFFFF;
/// The application version `dfu genpkg` writes when none is given
/// (`package.py:82`). Not checked by the bootloader.
pub const APPLICATION_VERSION_ANY: u32 = 0xFFFF_FFFF;
/// The line speed `dfu serial -b 115200` opens the port at.
pub const BAUD: u32 = 115_200;

/// Largest data payload in one frame (`DFU_PACKET_MAX_SIZE`).
pub const MAX_DATA: usize = 512;
/// How often a frame is sent before a missing or wrong acknowledgement
/// fails the flash. The reference's own (unreached) limit is three
/// (`dfu_transport_serial.py:252`).
pub const SEND_ATTEMPTS: usize = 3;
/// How long to wait for an acknowledgement (`ACK_PACKET_TIMEOUT`).
pub const ACK_TIMEOUT: Duration = Duration::from_secs(1);

const PACKET_INIT: u32 = 1;
const PACKET_START: u32 = 3;
const PACKET_DATA: u32 = 4;
const PACKET_STOP: u32 = 5;
const MODE_APPLICATION: u32 = 4;

const HCI_PACKET_TYPE: u8 = 14;
const DATA_INTEGRITY_CHECK_PRESENT: u8 = 1;
const RELIABLE_PACKET: u8 = 1;

const SLIP_END: u8 = 0xC0;
const SLIP_ESC: u8 = 0xDB;
const SLIP_ESC_END: u8 = 0xDC;
const SLIP_ESC_ESC: u8 = 0xDD;

/// Below this the reference never takes image bytes from a hex: it is the
/// MBR (`nrfhex.py:44`, `:109-116`).
const MBR_END: u32 = 0x1000;

/// The flash timing the reference paces the transfer by. Not protocol: the
/// bootloader acknowledges a frame on arrival and erases or writes flash
/// afterwards with its CPU blocked, so a host that sends faster than that
/// overruns its receive buffers (`dfu_transport_serial.py:59-74`, `:219-221`).
const FLASH_PAGE: usize = 4096;
const PAGE_ERASE: Duration = Duration::from_micros(89_700);
const PAGE_WRITE: Duration = Duration::from_micros((FLASH_PAGE as u64 / 4) * 100);

#[derive(Debug, thiserror::Error)]
pub enum Error {
    #[error("the image is empty")]
    Empty,
    #[error(
        "the image starts at {low:#x}, and this bootloader writes an application to {app_base:#x} \
         whatever it was linked for; it would not boot. Nothing was sent."
    )]
    NotAtAppBase { low: u32, app_base: u32 },
    #[error("the image is {len} bytes, more than a start packet can announce")]
    TooLarge { len: usize },
    #[error("{stage}: the bootloader did not answer, {attempts} times in a row")]
    Silent { stage: Stage, attempts: usize },
    #[error(
        "{stage}: the bootloader acknowledged {got} where {expected} takes this frame, \
         {attempts} times in a row"
    )]
    Nack {
        stage: Stage,
        expected: u8,
        got: u8,
        attempts: usize,
    },
    #[error("{stage}: the port went away ({detail})")]
    Gone { stage: Stage, detail: String },
    #[error("{stage}: {source}")]
    Io {
        stage: Stage,
        #[source]
        source: io::Error,
    },
}

impl Error {
    /// The frame the transfer stopped at, when it got as far as sending one.
    pub fn stage(&self) -> Option<Stage> {
        match self {
            Error::Silent { stage, .. }
            | Error::Nack { stage, .. }
            | Error::Gone { stage, .. }
            | Error::Io { stage, .. } => Some(*stage),
            Error::Empty | Error::NotAtAppBase { .. } | Error::TooLarge { .. } => None,
        }
    }
}

/// Which frame of a transfer something happened at.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Stage {
    Start,
    Init,
    /// One-based, out of `of`.
    Data {
        index: usize,
        of: usize,
    },
    Stop,
}

impl Stage {
    /// Whether the bootloader had already erased the application area when
    /// the transfer stopped here. It erases on the start packet, before the
    /// init packet is checked, so every stage after an acknowledged start
    /// leaves the board with no application.
    pub fn erased_before(self) -> bool {
        !matches!(self, Stage::Start)
    }
}

impl fmt::Display for Stage {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Stage::Start => write!(f, "the start packet"),
            Stage::Init => write!(f, "the init packet"),
            Stage::Data { index, of } => write!(f, "data frame {index} of {of}"),
            Stage::Stop => write!(f, "the stop packet"),
        }
    }
}

/// What the catalogue states about a board's serial-DFU bootloader: the two
/// init-packet fields it checks.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Params {
    /// `--dev-type`. `0x0052` on every Adafruit nRF52 bootloader.
    pub device_type: u16,
    /// `--sd-req`: the firmware IDs of the SoftDevices the image may land
    /// on. The bootloader refuses the image unless the one it runs is here.
    pub sd_req: Vec<u16>,
}

/// The init packet as `dfu genpkg` builds it for DFU version 0.5, the
/// version it uses unless told otherwise.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InitPacket {
    pub device_type: u16,
    pub device_revision: u16,
    pub application_version: u32,
    pub sd_req: Vec<u16>,
    /// CRC16 of the whole image, checked by the bootloader after the stop
    /// packet (`dfu_init.c`, `dfu_init_postvalidate`).
    pub image_crc: u16,
}

impl InitPacket {
    pub fn encode(&self) -> Vec<u8> {
        let mut out = Vec::with_capacity(12 + 2 * self.sd_req.len());
        out.extend_from_slice(&self.device_type.to_le_bytes());
        out.extend_from_slice(&self.device_revision.to_le_bytes());
        out.extend_from_slice(&self.application_version.to_le_bytes());
        out.extend_from_slice(&(self.sd_req.len() as u16).to_le_bytes());
        for fwid in &self.sd_req {
            out.extend_from_slice(&fwid.to_le_bytes());
        }
        out.extend_from_slice(&self.image_crc.to_le_bytes());
        out
    }
}

/// One application image, ready to send: the bytes and the init packet that
/// describes them.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Package {
    pub init: InitPacket,
    pub firmware: Vec<u8>,
}

impl Package {
    pub fn new(params: &Params, firmware: Vec<u8>) -> Self {
        Self {
            init: InitPacket {
                device_type: params.device_type,
                device_revision: DEVICE_REVISION_ANY,
                application_version: APPLICATION_VERSION_ANY,
                sd_req: params.sd_req.clone(),
                image_crc: crc16(&firmware, 0xFFFF),
            },
            firmware,
        }
    }

    /// How many data frames the image takes.
    pub fn data_frames(&self) -> usize {
        self.firmware.len().div_ceil(MAX_DATA)
    }

    /// The parameters, in the words `dfu genpkg` takes them, for a dry run
    /// and for the plan a real run shows before it writes.
    pub fn describe(&self) -> String {
        let sd: Vec<String> = self
            .init
            .sd_req
            .iter()
            .map(|fwid| format!("{fwid:#06x}"))
            .collect();
        format!(
            "device type {:#06x}, device revision {:#06x}, application version {:#010x}, \
             SoftDevice requirement {}, {} bytes in {} data frames, image CRC16 {:#06x}",
            self.init.device_type,
            self.init.device_revision,
            self.init.application_version,
            sd.join(","),
            self.firmware.len(),
            self.data_frames(),
            self.init.image_crc
        )
    }
}

/// The CRC16 the protocol uses, for frames and for the image
/// (`crc16.py:160-176`): CRC-CCITT with the byte-swap formulation Nordic's
/// SDK uses, so the same code checks it on the board.
pub fn crc16(data: &[u8], init: u16) -> u16 {
    let mut crc = init;
    for &byte in data {
        crc = crc.rotate_left(8);
        crc ^= u16::from(byte);
        crc ^= (crc & 0x00FF) >> 4;
        crc ^= crc << 12;
        crc ^= (crc & 0x00FF) << 5;
    }
    crc
}

/// The image bytes the reference would send for these spans: from the
/// lowest address to the highest, `0xFF` wherever no span reaches, rounded
/// up to a whole word (`nrfhex.py:118-143`). The first byte has to be at
/// `app_base`, because that is where the bootloader puts it.
pub fn firmware(spans: &[Span], app_base: u32) -> Result<Vec<u8>, Error> {
    let present = spans.iter().filter(|s| !s.is_empty() && s.end() > MBR_END);
    let low = present
        .clone()
        .map(|s| s.start.max(MBR_END))
        .min()
        .ok_or(Error::Empty)?;
    let high = present.clone().map(Span::end).max().ok_or(Error::Empty)?;
    if low != app_base {
        return Err(Error::NotAtAppBase { low, app_base });
    }
    let len = ((high - low) as usize).next_multiple_of(4);
    if u32::try_from(len).is_err() {
        return Err(Error::TooLarge { len });
    }
    let mut out = vec![0xFFu8; len];
    for span in present {
        let skip = MBR_END.saturating_sub(span.start) as usize;
        let at = (span.start.max(MBR_END) - low) as usize;
        let data = &span.data[skip..];
        out[at..at + data.len()].copy_from_slice(data);
    }
    Ok(out)
}

/// The spans a UF2 image covers, adjacent blocks joined, so a UF2 payload
/// and the hex it was made from give [`firmware`] the same input up to the
/// zero padding the UF2 carries to the end of its last block.
pub fn image_spans(image: &Image) -> Vec<Span> {
    let mut blocks: Vec<_> = image.blocks.iter().collect();
    blocks.sort_by_key(|b| b.target_addr);
    let mut out: Vec<Span> = Vec::new();
    for block in blocks {
        match out.last_mut() {
            Some(last) if last.end() == block.target_addr => {
                last.data.extend_from_slice(&block.data)
            }
            _ => out.push(Span {
                start: block.target_addr,
                data: block.data.clone(),
            }),
        }
    }
    out
}

/// The four header bytes in front of every frame (`util.py:82-102`).
pub fn header(seq: u8, len: usize) -> [u8; 4] {
    let seq = seq & 0x07;
    let mut h = [0u8; 4];
    h[0] =
        seq | (((seq + 1) % 8) << 3) | (DATA_INTEGRITY_CHECK_PRESENT << 6) | (RELIABLE_PACKET << 7);
    h[1] = HCI_PACKET_TYPE | (((len & 0x000F) as u8) << 4);
    h[2] = ((len & 0x0FF0) >> 4) as u8;
    h[3] = header_checksum(&h[..3]);
    h
}

fn header_checksum(first_three: &[u8]) -> u8 {
    first_three
        .iter()
        .fold(0u8, |sum, b| sum.wrapping_add(*b))
        .wrapping_neg()
}

/// One frame on the wire: header, payload and CRC, SLIP-escaped between two
/// `0xC0` (`dfu_transport_serial.py:337-366`).
pub fn frame(seq: u8, payload: &[u8]) -> Vec<u8> {
    let mut body = Vec::with_capacity(payload.len() + 6);
    body.extend_from_slice(&header(seq, payload.len()));
    body.extend_from_slice(payload);
    let crc = crc16(&body, 0xFFFF);
    body.extend_from_slice(&crc.to_le_bytes());

    let mut out = Vec::with_capacity(body.len() + body.len() / 8 + 2);
    out.push(SLIP_END);
    slip_escape(&body, &mut out);
    out.push(SLIP_END);
    out
}

fn slip_escape(data: &[u8], out: &mut Vec<u8>) {
    for &byte in data {
        match byte {
            SLIP_END => out.extend_from_slice(&[SLIP_ESC, SLIP_ESC_END]),
            SLIP_ESC => out.extend_from_slice(&[SLIP_ESC, SLIP_ESC_ESC]),
            other => out.push(other),
        }
    }
}

/// Undo the escaping [`frame`] applies. `None` for an escape byte followed by anything but
/// the two it may be followed by — a damaged frame, which the reference
/// raises on and which is dropped here like any other damaged frame.
pub fn slip_unescape(data: &[u8]) -> Option<Vec<u8>> {
    let mut out = Vec::with_capacity(data.len());
    let mut bytes = data.iter();
    while let Some(&byte) = bytes.next() {
        if byte == SLIP_ESC {
            match bytes.next() {
                Some(&SLIP_ESC_END) => out.push(SLIP_END),
                Some(&SLIP_ESC_ESC) => out.push(SLIP_ESC),
                _ => return None,
            }
        } else {
            out.push(byte);
        }
    }
    Some(out)
}

/// The start packet: an application of `len` bytes, nothing else.
pub fn start_payload(len: u32) -> Vec<u8> {
    let mut out = Vec::with_capacity(20);
    out.extend_from_slice(&PACKET_START.to_le_bytes());
    out.extend_from_slice(&MODE_APPLICATION.to_le_bytes());
    out.extend_from_slice(&0u32.to_le_bytes()); // SoftDevice
    out.extend_from_slice(&0u32.to_le_bytes()); // bootloader
    out.extend_from_slice(&len.to_le_bytes());
    out
}

/// The init packet frame's payload, with the two bytes of padding the
/// reference adds (`dfu_transport_serial.py:152`): the bootloader counts
/// payloads in words.
pub fn init_payload(init: &InitPacket) -> Vec<u8> {
    let mut out = PACKET_INIT.to_le_bytes().to_vec();
    out.extend_from_slice(&init.encode());
    out.extend_from_slice(&[0, 0]);
    out
}

pub fn data_payload(chunk: &[u8]) -> Vec<u8> {
    let mut out = PACKET_DATA.to_le_bytes().to_vec();
    out.extend_from_slice(chunk);
    out
}

pub fn stop_payload() -> Vec<u8> {
    PACKET_STOP.to_le_bytes().to_vec()
}

/// Every frame a transfer of `package` writes, in order, numbered from one:
/// what the reference writes for the same package when every frame is
/// acknowledged the first time.
pub fn frames(package: &Package) -> Vec<Vec<u8>> {
    let mut payloads = vec![
        start_payload(package.firmware.len() as u32),
        init_payload(&package.init),
    ];
    payloads.extend(package.firmware.chunks(MAX_DATA).map(data_payload));
    payloads.push(stop_payload());
    payloads
        .iter()
        .enumerate()
        .map(|(i, payload)| frame(((i + 1) % 8) as u8, payload))
        .collect()
}

/// How long the reference waits after the start packet for the erase
/// (`dfu_transport_serial.py:157-159`).
pub fn erase_wait(image_len: usize) -> Duration {
    let pages = (image_len / FLASH_PAGE + 1) as u32;
    (PAGE_ERASE * pages).max(Duration::from_millis(500))
}

/// How long the reference waits after the stop packet before it lets go of
/// the port, for a single-bank application update: one page erased and
/// written for the bootloader settings (`dfu_transport_serial.py:161-165`).
pub fn activate_wait() -> Duration {
    PAGE_ERASE + PAGE_WRITE
}

/// A port a transfer runs over. [`crate::sys::Fd`] on a board; a scripted
/// bootloader in the tests.
pub trait Link {
    fn write(&mut self, bytes: &[u8]) -> io::Result<()>;
    /// One read, waiting up to `timeout`. `Ok(Some(empty))` is nothing yet,
    /// `Ok(None)` the end of the port: the device went away.
    fn read(&mut self, timeout: Duration) -> io::Result<Option<Vec<u8>>>;
}

impl Link for crate::sys::Fd {
    fn write(&mut self, bytes: &[u8]) -> io::Result<()> {
        // A full frame is about 45 ms of line time at 115200 baud.
        self.write_all(bytes, Instant::now() + Duration::from_secs(2))
    }

    fn read(&mut self, timeout: Duration) -> io::Result<Option<Vec<u8>>> {
        self.read_available(timeout)
    }
}

/// What a transfer did.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Sent {
    pub bytes: usize,
    pub data_frames: usize,
    /// Frames sent more than once, after a NACK or a silence.
    pub resent: usize,
    /// The port went away after the stop packet was written and before its
    /// acknowledgement was read. The bootloader resets as it activates an
    /// image, so this is not a failure the transfer can call: whether the
    /// image took is for the boot check to say, as it is for every flash.
    pub stop_unacknowledged: bool,
}

/// Send `package` as an application update: start, init, data, stop, each
/// frame acknowledged before the next goes out, paced the way the reference
/// paces it. `pause` is the clock, so the tests run without waiting;
/// `progress` hears every acknowledged data frame.
pub fn send(
    link: &mut dyn Link,
    package: &Package,
    pause: &mut dyn FnMut(Duration),
    progress: &mut dyn FnMut(usize, usize),
) -> Result<Sent, Error> {
    if package.firmware.is_empty() {
        return Err(Error::Empty);
    }
    let len = u32::try_from(package.firmware.len()).map_err(|_| Error::TooLarge {
        len: package.firmware.len(),
    })?;
    let mut session = Session {
        link,
        seq: 0,
        rx: Vec::new(),
        resent: 0,
    };

    session.send(&start_payload(len), Stage::Start)?;
    pause(erase_wait(package.firmware.len()));
    session.send(&init_payload(&package.init), Stage::Init)?;

    let of = package.data_frames();
    for (i, chunk) in package.firmware.chunks(MAX_DATA).enumerate() {
        session.send(&data_payload(chunk), Stage::Data { index: i + 1, of })?;
        progress(i + 1, of);
        if i % 8 == 0 {
            pause(PAGE_WRITE);
        }
    }
    pause(PAGE_WRITE);
    let stop_unacknowledged = match session.send(&stop_payload(), Stage::Stop) {
        Ok(()) => false,
        Err(Error::Gone { .. }) => true,
        Err(other) => return Err(other),
    };
    pause(activate_wait());

    Ok(Sent {
        bytes: package.firmware.len(),
        data_frames: of,
        resent: session.resent,
        stop_unacknowledged,
    })
}

struct Session<'a> {
    link: &'a mut dyn Link,
    /// The number of the last frame sent.
    seq: u8,
    /// Bytes read and not yet made into an acknowledgement.
    rx: Vec<u8>,
    resent: usize,
}

enum Heard {
    Ack(u8),
    Silence,
}

impl Session<'_> {
    fn send(&mut self, payload: &[u8], stage: Stage) -> Result<(), Error> {
        self.seq = (self.seq + 1) % 8;
        let bytes = frame(self.seq, payload);
        let expected = (self.seq + 1) % 8;
        let mut last = Heard::Silence;
        for attempt in 1..=SEND_ATTEMPTS {
            if attempt > 1 {
                self.resent += 1;
            }
            self.link
                .write(&bytes)
                .map_err(|source| gone_or_io(stage, source))?;
            last = self.ack(stage)?;
            if matches!(last, Heard::Ack(n) if n == expected) {
                return Ok(());
            }
        }
        Err(match last {
            Heard::Ack(got) => Error::Nack {
                stage,
                expected,
                got,
                attempts: SEND_ATTEMPTS,
            },
            Heard::Silence => Error::Silent {
                stage,
                attempts: SEND_ATTEMPTS,
            },
        })
    }

    /// The next acknowledgement, or silence once [`ACK_TIMEOUT`] passes.
    /// Anything that does not decode as one — a damaged frame, a stray byte
    /// — is skipped rather than read as an answer.
    fn ack(&mut self, stage: Stage) -> Result<Heard, Error> {
        let deadline = Instant::now() + ACK_TIMEOUT;
        loop {
            while let Some(body) = next_slip_frame(&mut self.rx) {
                if let Some(n) = decode_ack(&body) {
                    return Ok(Heard::Ack(n));
                }
            }
            let remaining = deadline.saturating_duration_since(Instant::now());
            if remaining.is_zero() {
                return Ok(Heard::Silence);
            }
            match self.link.read(remaining) {
                Ok(Some(bytes)) => self.rx.extend_from_slice(&bytes),
                Ok(None) => {
                    return Err(Error::Gone {
                        stage,
                        detail: "end of file".into(),
                    })
                }
                Err(source) => return Err(gone_or_io(stage, source)),
            }
        }
    }
}

/// An I/O error from a port that vanished is the board resetting, which
/// says something different from a port that refused a write.
fn gone_or_io(stage: Stage, source: io::Error) -> Error {
    if crate::transport::is_bootloader_reboot(&source) {
        Error::Gone {
            stage,
            detail: source.to_string(),
        }
    } else {
        Error::Io { stage, source }
    }
}

/// Take the next complete, non-empty SLIP frame off the front of `rx`,
/// unescaped. Bytes before the first `0xC0` are noise and dropped; an empty
/// frame (two `0xC0` back to back, the end of one frame and the start of
/// the next) is skipped.
fn next_slip_frame(rx: &mut Vec<u8>) -> Option<Vec<u8>> {
    loop {
        let start = rx.iter().position(|&b| b == SLIP_END)?;
        let end = start + 1 + rx[start + 1..].iter().position(|&b| b == SLIP_END)?;
        let body: Vec<u8> = rx[start + 1..end].to_vec();
        // The closing 0xC0 stays: if the next frame shares it as its opener
        // it is needed, and if the next frame brings its own, the two read
        // as an empty frame and are skipped.
        rx.drain(..end);
        if body.is_empty() {
            continue;
        }
        match slip_unescape(&body) {
            Some(body) => return Some(body),
            None => continue,
        }
    }
}

/// The acknowledgement number of an ack frame: four header bytes whose
/// checksum holds (`hci_transport.c`, `ack_transmit`).
fn decode_ack(body: &[u8]) -> Option<u8> {
    if body.len() != 4 || header_checksum(&body[..3]) != body[3] {
        return None;
    }
    Some((body[0] >> 3) & 0x07)
}

/// A bootloader in software, for the tests: the receive side of the Adafruit
/// nRF52 bootloader's serial DFU, close enough that a transfer this module
/// sends is checked the way the board checks it.
///
/// Modelled on the bootloader source (`hci_transport.c`,
/// `dfu_transport_serial.c`, `dfu_single_bank.c`, `dfu_init.c`):
///
/// * a frame is taken only if its length, integrity and reliable bits,
///   packet type, header checksum, length field and CRC all hold; a damaged
///   frame is dropped without an answer;
/// * a frame with the expected number is acknowledged with the next one, any
///   other number with the number still expected;
/// * the start packet erases, the init packet is checked for device type
///   `0x0052` and for the SoftDevice it runs, and a refusal resets the
///   board, after the init frame was acknowledged;
/// * the stop packet checks the image against the init packet's CRC16 and
///   activates it; either way the board resets.
///
/// A reset ends the port: reads see end of file and writes fail.
#[cfg(test)]
pub(crate) mod fake {
    use super::*;

    pub const ADAFRUIT_DEVICE_TYPE: u16 = 0x0052;
    /// `DFU_SOFTDEVICE_ANY` in the SDK.
    pub const SOFTDEVICE_ANY: u16 = 0xFFFE;
    /// S140 7.3.0, what the T1000-E runs.
    pub const S140_7_3_0: u16 = 0x0123;

    #[derive(Debug, Clone, PartialEq, Eq)]
    pub enum Ended {
        /// The init packet was refused and the board reset.
        Refused(&'static str),
        /// The stop packet arrived and the image checked out.
        Activated,
        /// The stop packet arrived and the image did not check out.
        BadImage,
    }

    #[derive(Debug)]
    pub struct Bootloader {
        /// The firmware ID of the SoftDevice it runs.
        pub softdevice: u16,
        /// NACK the data frame with this one-based index this many times.
        pub nack_data: Option<(usize, usize)>,
        /// Drop every frame from this one (one-based, counting all frames)
        /// on without an answer: a line that died.
        pub deaf_from: Option<usize>,
        expected: u8,
        rx: Vec<u8>,
        out: Vec<u8>,
        frames_taken: usize,
        frames_heard: usize,
        data_frames: usize,
        pub erased: bool,
        pub image_size: Option<u32>,
        pub init: Option<Vec<u8>>,
        pub image: Vec<u8>,
        pub ended: Option<Ended>,
        /// Every frame that was acknowledged as taken, as it arrived.
        pub taken: Vec<Vec<u8>>,
    }

    impl Bootloader {
        pub fn new(softdevice: u16) -> Self {
            Self {
                softdevice,
                nack_data: None,
                deaf_from: None,
                expected: 1,
                rx: Vec::new(),
                out: Vec::new(),
                frames_taken: 0,
                frames_heard: 0,
                data_frames: 0,
                erased: false,
                image_size: None,
                init: None,
                image: Vec::new(),
                ended: None,
                taken: Vec::new(),
            }
        }

        pub fn is_gone(&self) -> bool {
            self.ended.is_some()
        }

        /// Feed bytes from the host; what the bootloader answers is queued
        /// for [`Link::read`].
        pub fn feed(&mut self, bytes: &[u8]) {
            self.rx.extend_from_slice(bytes);
            while !self.is_gone() {
                let Some(body) = next_slip_frame(&mut self.rx) else {
                    return;
                };
                self.frame(&body);
            }
        }

        fn ack(&mut self) {
            let mut h = [(self.expected & 0x07) << 3, 0, 0, 0];
            h[3] = header_checksum(&h[..3]);
            self.out.push(SLIP_END);
            slip_escape(&h, &mut self.out);
            self.out.push(SLIP_END);
        }

        fn frame(&mut self, body: &[u8]) {
            self.frames_heard += 1;
            if self.deaf_from.is_some_and(|n| self.frames_heard >= n) {
                return;
            }
            if !valid(body) {
                return;
            }
            let seq = body[0] & 0x07;
            if seq != self.expected {
                self.ack();
                return;
            }
            let payload = &body[4..body.len() - 2];
            let kind = u32::from_le_bytes([payload[0], payload[1], payload[2], payload[3]]);
            if kind == PACKET_DATA {
                let index = self.data_frames + 1;
                if let Some((at, times)) = self.nack_data.as_mut() {
                    if *at == index && *times > 0 {
                        *times -= 1;
                        self.ack();
                        return;
                    }
                }
            }
            self.expected = (self.expected + 1) % 8;
            self.ack();
            self.frames_taken += 1;
            self.taken.push(body.to_vec());
            self.process(kind, &payload[4..]);
        }

        fn process(&mut self, kind: u32, rest: &[u8]) {
            match kind {
                PACKET_START => {
                    let word = |i: usize| {
                        u32::from_le_bytes([rest[i], rest[i + 1], rest[i + 2], rest[i + 3]])
                    };
                    assert_eq!(word(0), MODE_APPLICATION, "only applications are modelled");
                    self.image_size = Some(word(4) + word(8) + word(12));
                    self.erased = true;
                }
                PACKET_INIT => {
                    self.init = Some(rest.to_vec());
                    if let Err(why) = self.prevalidate(rest) {
                        self.ended = Some(Ended::Refused(why));
                    }
                }
                PACKET_DATA => {
                    self.data_frames += 1;
                    self.image.extend_from_slice(rest);
                }
                PACKET_STOP => {
                    let ok = self.postvalidate();
                    self.ended = Some(if ok {
                        Ended::Activated
                    } else {
                        Ended::BadImage
                    });
                }
                _ => {}
            }
        }

        fn prevalidate(&self, init: &[u8]) -> Result<(), &'static str> {
            let u16_at = |i: usize| u16::from_le_bytes([init[i], init[i + 1]]);
            if init.len() < 12 {
                return Err("init packet too short");
            }
            if u16_at(0) != ADAFRUIT_DEVICE_TYPE {
                return Err("device type");
            }
            let count = usize::from(u16_at(8));
            if init.len() < 10 + 2 * count + 2 {
                return Err("init packet too short");
            }
            if (0..count)
                .map(|i| u16_at(10 + 2 * i))
                .any(|fwid| fwid == SOFTDEVICE_ANY || fwid == self.softdevice)
            {
                Ok(())
            } else {
                Err("SoftDevice requirement")
            }
        }

        fn postvalidate(&self) -> bool {
            let Some(init) = &self.init else {
                return false;
            };
            let count = usize::from(u16::from_le_bytes([init[8], init[9]]));
            let at = 10 + 2 * count;
            let crc = u16::from_le_bytes([init[at], init[at + 1]]);
            Some(self.image.len() as u32) == self.image_size && crc16(&self.image, 0xFFFF) == crc
        }
    }

    fn valid(body: &[u8]) -> bool {
        if body.len() <= 4 + 2 {
            return false;
        }
        if body[0] & 0x40 == 0 || body[0] & 0x80 == 0 {
            return false;
        }
        if body[1] & 0x0F != HCI_PACKET_TYPE {
            return false;
        }
        if header_checksum(&body[..3]) != body[3] {
            return false;
        }
        let len = usize::from(body[1] >> 4) | (usize::from(body[2]) << 4);
        if len + 6 != body.len() {
            return false;
        }
        let crc = u16::from_le_bytes([body[body.len() - 2], body[body.len() - 1]]);
        crc16(&body[..body.len() - 2], 0xFFFF) == crc
    }

    impl Link for Bootloader {
        fn write(&mut self, bytes: &[u8]) -> io::Result<()> {
            if self.is_gone() {
                return Err(io::Error::from_raw_os_error(libc::EIO));
            }
            self.feed(bytes);
            Ok(())
        }

        fn read(&mut self, _timeout: Duration) -> io::Result<Option<Vec<u8>>> {
            if !self.out.is_empty() {
                return Ok(Some(std::mem::take(&mut self.out)));
            }
            if self.is_gone() {
                return Ok(None);
            }
            Ok(Some(Vec::new()))
        }
    }
}

